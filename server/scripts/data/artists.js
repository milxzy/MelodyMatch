// Get all unique artists across all genres
export function getAllArtists() {
  const allArtists = new Set();
  Object.values(artistsByGenre).forEach(artists => {
    artists.forEach(artist => allArtists.add(artist));
  });
  return Array.from(allArtists);
}

// Get artists for specific genres
export function getArtistsForGenres(genres) {
  const artists = new Set();
  genres.forEach(genre => {
    const genreArtists = artistsByGenre[genre] || [];
    genreArtists.forEach(artist => artists.add(artist));
  });
  return Array.from(artists);
}

// Get random artists from a genre
export function getRandomArtistsFromGenre(genre, count) {
  const genreArtists = artistsByGenre[genre] || [];
  const shuffled = [...genreArtists].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, genreArtists.length));
}
